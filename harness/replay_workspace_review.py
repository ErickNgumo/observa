"""Real-browser OBS-UI-01 checks and screenshots. Start observa.replay first.
Usage: python harness/replay_workspace_review.py [http://127.0.0.1:8765]
Requires development-only playwright and a Chromium installation.
"""
import json
import os
from pathlib import Path
import sys
from playwright.sync_api import sync_playwright

URL = sys.argv[1] if len(sys.argv) > 1 else 'http://127.0.0.1:8765'
OUT = Path('docs/engineering/obs-ui-01-screenshots')
OUT.mkdir(parents=True, exist_ok=True)
checks = []

def check(label, condition):
    assert condition, label
    checks.append(label)
    print('PASS', label)

def stable(page):
    page.wait_for_function("Math.abs(document.querySelector('#bottom-panel').getBoundingClientRect().height - (workspaceState.collapsed ? 40 : workspaceState.height)) < 0.1")
    page.wait_for_timeout(150)  # allow ResizeObserver and chart canvas paint

def screenshot(page, name):
    stable(page)
    page.screenshot(path=str(OUT / (name + '.png')))

def geometry(page):
    return page.evaluate('''() => ({width:innerWidth, body:document.body.scrollWidth,
      chart:document.querySelector('#chart').clientHeight,
      panel:document.querySelector('#bottom-panel').getBoundingClientRect().height,
      tabs:document.querySelector('#panel-tabs').getBoundingClientRect().bottom,
      viewport:innerHeight})''')

with sync_playwright() as p:
    executable = os.environ.get('OBSERVA_CHROMIUM')
    browser = p.chromium.launch(headless=True, executable_path=executable)
    page = browser.new_page(viewport={'width':1920,'height':1080})
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.goto(URL)
    page.wait_for_function('payload !== null && replayIndex !== null')
    check('real EUR/USD demo metadata', page.locator('#stat-pair').inner_text() == 'EURUSD · 15m')
    check('empty Trade Log is explicit', page.locator('#trade-log-body').inner_text() == 'No closed trades yet')
    page.click('#btn-end')
    stable(page)
    check('11 recorded closed trades', page.locator('#trade-log-body tr').count() == 11)
    check('no desktop page overflow', geometry(page)['body'] == 1920)
    screenshot(page, '01-main-default-1920')
    page.click('#panel-toggle')
    stable(page)
    check('inspector collapses to tab strip', geometry(page)['panel'] == 40)
    screenshot(page, '02-main-collapsed-1920')
    page.click('[data-panel="trades"]')
    stable(page)
    check('tab click expands collapsed inspector', geometry(page)['panel'] == 280)
    scroll = page.locator('#trade-log').evaluate('(el) => ({height:el.clientHeight, scroll:el.scrollHeight})')
    check('Trade Log independently overflows', scroll['scroll'] > scroll['height'])
    top = page.locator('#trade-log th').first.bounding_box()['y']
    page.locator('#trade-log').evaluate('(el) => el.scrollTop = el.scrollHeight')
    check('sticky header stays in place', abs(page.locator('#trade-log th').first.bounding_box()['y'] - top) < 1)
    check('Trade Log does not scroll page', page.evaluate('window.scrollY') == 0)
    page.locator('#trade-log').evaluate('(el) => el.scrollTop = 0')
    page.locator('#trade-log-body tr').nth(1).click()
    check('trade selection pauses follow and preserves replay bar', page.evaluate('!chartFollowing && selectedTradeId !== null && currentBar === 599'))
    check('trade selection is visible', page.locator('#trade-log-body tr.is-selected').count() == 1)
    check('trade chart highlight exists', page.locator('#investigation-overlay').count() == 1)
    screenshot(page, '03-trade-log-1920')
    page.click('#btn-follow')
    page.click('[data-panel="replay"]')
    handle=page.locator('#panel-resize-handle').bounding_box()
    page.mouse.move(handle['x']+handle['width']/2, handle['y']+4)
    page.mouse.down()
    page.mouse.move(handle['x']+handle['width']/2, handle['y']-290, steps=15)
    page.mouse.up()
    stable(page)
    check('pointer resize expands inspector', geometry(page)['panel'] > 550)
    check('resized chart remains usable', geometry(page)['chart'] >= 200)
    screenshot(page, '04-inspector-expanded-1920')
    page.locator('#replay-panel').evaluate('(el) => el.scrollTop = el.scrollHeight')
    page.locator('#bar-events details').first.locator('summary').click()
    check('events expose exact recorded details', page.locator('#bar-events details[open] pre').count() == 1)
    screenshot(page, '05-inspector-events-1920')
    page.click('[data-panel="metrics"]')
    check('six primary metrics', page.locator('.primary-metrics .metric-card').count() == 6)
    screenshot(page, '06-metrics-1920')
    page.click('[data-panel="equity"]')
    screenshot(page, '07-equity-expanded-1920')
    page.locator('#panel-resize-handle').dblclick()
    stable(page)
    check('double-click resets height', geometry(page)['panel'] == 280)
    page.locator('#panel-resize-handle').focus()
    page.keyboard.press('ArrowUp')
    check('keyboard resize updates accessible value', page.locator('#panel-resize-handle').get_attribute('aria-valuenow') == '304')
    page.reload()
    page.wait_for_function('payload !== null')
    stable(page)
    check('height survives session reload', geometry(page)['panel'] == 304)
    page.evaluate('renderToBar(300)')
    spacing = page.evaluate('chart.timeScale().options().barSpacing')
    page.evaluate('for (var n=301;n<340;n++) renderToBar(n)')
    stable(page)
    check('follow preserves candle spacing', abs(page.evaluate('chart.timeScale().options().barSpacing') - spacing) < 0.1)
    pos = page.evaluate('chart.timeScale().timeToCoordinate(candleData[candleData.length-1].time) / chart.timeScale().width()')
    check('latest candle 75–85% across viewport', 0.75 <= pos <= 0.85)
    box = page.locator('#chart').bounding_box()
    page.mouse.move(box['x']+500, box['y']+150)
    page.mouse.wheel(0, -180)
    stable(page)
    check('wheel zoom pauses follow', page.evaluate('!chartFollowing'))
    held = page.evaluate('chart.timeScale().getVisibleLogicalRange()')
    page.evaluate('renderToBar(currentBar+1)')
    now = page.evaluate('chart.timeScale().getVisibleLogicalRange()')
    check('replay preserves manually zoomed viewport', abs(held['from']-now['from']) < 0.1 and abs(held['to']-now['to']) < 0.1)
    page.click('#btn-follow')
    page.mouse.move(box['x']+500, box['y']+150)
    page.mouse.down()
    page.mouse.move(box['x']+600, box['y']+150, steps=10)
    page.mouse.up()
    check('drag pan pauses follow', page.evaluate('!chartFollowing'))
    page.click('#btn-follow')
    page.select_option('#speed-select', '10')
    page.click('#btn-play')
    page.wait_for_function('currentBar >= 365')
    page.click('#btn-play')
    check('actual replay timer advances and pauses', page.evaluate('currentBar >= 365 && !isPlaying'))
    page.get_by_role('button', name='Fit all', exact=True).click()
    check('Fit all is distinct from follow', page.evaluate('!chartFollowing'))
    coordinate = page.evaluate('({x:chart.timeScale().timeToCoordinate(candleData[200].time),y:candleSeries.priceToCoordinate(candleData[200].close)})')
    page.mouse.click(box['x']+coordinate['x'], box['y']+coordinate['y'])
    check('candle click selects bar and Inspector', page.evaluate('currentBar === 200 && workspaceState.activeTab === "replay"'))
    check('chart seek restores Play control', page.locator('#btn-play').is_enabled())
    check('backward seek removes future drawdown overlays', page.evaluate('!investigationOutlines["max-drawdown"]'))
    page.click('#btn-end')
    page.set_viewport_size({'width':1366,'height':768})
    page.locator('#panel-resize-handle').dblclick()
    stable(page)
    check('laptop layout has no horizontal overflow', geometry(page)['body'] == 1366)
    check('laptop chart remains usable', geometry(page)['chart'] >= 200)
    check('laptop toolbar stays inside viewport', page.locator('#theme-select').bounding_box()['x'] + page.locator('#theme-select').bounding_box()['width'] <= 1366)
    screenshot(page, '08-inspector-1366')
    page.click('[data-panel="trades"]')
    screenshot(page, '09-trade-log-1366')
    page.click('[data-panel="metrics"]')
    page.locator('#panel-resize-handle').focus()
    for _ in range(20): page.keyboard.press('ArrowUp')
    stable(page)
    check('laptop resize respects chart minimum', geometry(page)['chart'] >= 190)
    screenshot(page, '10-metrics-expanded-1366')
    page.click('[data-panel="equity"]')
    page.locator('#panel-resize-handle').dblclick()
    screenshot(page, '11-equity-1366')
    page.click('#btn-reset')
    check('reset clears selected state and resumes follow', page.evaluate('currentBar === -1 && chartFollowing && selectedTradeId === null'))
    page.select_option('#theme-select', 'paper')
    page.click('#btn-end')
    screenshot(page, '12-light-theme-1366')
    page.select_option('#theme-select', 'midnight')
    page.set_viewport_size({'width':1920,'height':1080})
    page.evaluate("renderToBar(replayEvents.find(e => e.type === 'strategy_decision' && e.signals && e.signals.length).bar_index)")
    page.click('#btn-follow')
    page.click('[data-panel="replay"]')
    page.locator('#panel-resize-handle').focus()
    for _ in range(12): page.keyboard.press('ArrowUp')
    page.locator('#replay-panel').evaluate('(el) => el.scrollTop = 0')
    check('strategy reasons appear verbatim', 'EMA' in page.locator('#signal-reasons').inner_text())
    screenshot(page, '13-strategy-decision-1920')
    page.click('#btn-end')
    page.locator('#orders-body tr').first.focus()
    page.keyboard.press('Enter')
    check('order rows support keyboard selection', page.locator('#orders-body tr.is-selected').count() == 1)
    page.click('#btn-lines')
    check('annotations toggle preserves canonical markers', page.evaluate('!showAnnotations && tradeMarkers.length > 0'))
    page.click('#btn-lines')
    check('annotations restored', page.evaluate('showAnnotations'))
    check('no JavaScript errors', not errors)
    browser.close()
(OUT / 'checks.json').write_text(json.dumps({'url':URL, 'checks':checks, 'errors':errors}, indent=2) + '\n')
print(f'{len(checks)} browser checks passed')
