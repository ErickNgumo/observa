/// Which generic order kinds are enabled for a run.
///
/// The MVP supports MARKET, LIMIT and STOP; protective SL/TP are separate
/// concepts and are always available for open positions.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct OrderModelConfig {
    /// MARKET orders enabled (default: true).
    #[serde(default = "default_true")]
    pub market: bool,
    /// LIMIT orders enabled (default: true).
    #[serde(default = "default_true")]
    pub limit: bool,
    /// STOP orders enabled (default: true).
    #[serde(default = "default_true")]
    pub stop: bool,
}

impl Default for OrderModelConfig {
    fn default() -> Self {
        Self {
            market: true,
            limit: true,
            stop: true,
        }
    }
}

impl OrderModelConfig {
    /// Whether an order of the given kind is enabled.
    pub fn supports(&self, kind: OrderKind) -> bool {
        match kind {
            OrderKind::Market => self.market,
            OrderKind::Limit => self.limit,
            OrderKind::Stop => self.stop,
        }
    }
}

