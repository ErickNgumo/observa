// ────────────────────────────────────────────────
// Instrument configuration
// ────────────────────────────────────────────────

/// Instrument configuration — the market the strategy trades.
///
/// Monetary values derived from this config (units, notional, value-per-pip)
/// are computed by [`InstrumentConfig`] methods / [`crate::units`]; they are
/// never independently user-configurable inputs.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct InstrumentConfig {
    /// Instrument identifier, e.g. "EURUSD" (default: "EURUSD").
    #[serde(default = "default_symbol")]
    pub symbol: String,
    /// Base (instrument) currency code, e.g. "EUR".
    #[serde(default = "default_currency_eur")]
    pub base_currency: String,
    /// Quote (pricing) currency code, e.g. "USD".
    #[serde(default = "default_currency_usd")]
    pub quote_currency: String,
    /// Base units per 1 lot/contract (e.g. 100,000 for EURUSD; 1 for a stock).
    #[serde(default = "default_contract_size")]
    pub contract_size: f64,
    /// Price decimal places, e.g. 5 for EURUSD, 2 for a stock. Used to derive
    /// the default tick size when `tick_size` is not provided.
    #[serde(default = "default_price_decimals")]
    pub price_decimals: u32,
    /// Smallest price increment in price units. Derived as
    /// `10^-price_decimals` when omitted.
    #[serde(default)]
    pub tick_size: Option<f64>,
    /// One pip expressed in price units (e.g. 0.0001 for EURUSD). Optional;
    /// required only when pip-based value calculations are used downstream.
    #[serde(default)]
    pub pip_size: Option<f64>,
    /// Minimum tradable quantity, in lots (default: 0.01).
    #[serde(default = "default_min_quantity")]
    pub min_quantity: f64,
    /// Maximum tradable quantity, in lots (default: 100.0).
    #[serde(default = "default_max_quantity")]
    pub max_quantity: f64,
    /// Allowed quantity increment, in lots (default: 0.01).
    #[serde(default = "default_quantity_step")]
    pub quantity_step: f64,
}

impl Default for InstrumentConfig {
    fn default() -> Self {
        Self {
            symbol: default_symbol(),
            base_currency: default_currency_eur(),
            quote_currency: default_currency_usd(),
            contract_size: default_contract_size(),
            price_decimals: default_price_decimals(),
            tick_size: None,
            pip_size: None,
            min_quantity: default_min_quantity(),
            max_quantity: default_max_quantity(),
            quantity_step: default_quantity_step(),
        }
    }
}

impl InstrumentConfig {
    /// Base units for a position of `quantity_lots` lots:
    /// `units = quantity_lots × contract_size`.
    pub fn units(&self, quantity_lots: f64) -> f64 {
        quantity_lots * self.contract_size
    }

    /// Notional value of `quantity_lots` lots at `price`:
    /// `notional = units × price` (quote currency).
    pub fn notional(&self, quantity_lots: f64, price: f64) -> f64 {
        self.units(quantity_lots) * price
    }

    /// The effective tick size in price units: the configured value, or
    /// `10^-price_decimals` when only decimal precision is configured.
    pub fn effective_tick_size(&self) -> Result<f64, ConfigError> {
        match self.tick_size {
            Some(t) => Ok(t),
            None => Ok(10_f64.powi(-(self.price_decimals as i32))),
        }
    }

    /// Money value of one pip per lot = `pip_size × contract_size`.
    ///
    /// Requires `pip_size` to be configured; pip value is a derived quantity
    /// and is never a free input.
    pub fn pip_value_per_lot(&self) -> Result<f64, ConfigError> {
        let pip = self.pip_size.ok_or_else(|| ConfigError::InvalidField {
            field: "instrument.pip_size".into(),
            reason: "pip_size must be configured to derive monetary pip value".into(),
        })?;
        Ok(pip * self.contract_size)
    }
}

// ────────────────────────────────────────────────
// Bar interval
// ────────────────────────────────────────────────

/// The dataset bar interval (timeframe).
///
/// Required later for missing-data gap detection and metric annualization.
/// Serialized as a compact string, e.g. `"15m"`, `"4h"`, `"1d"`, `"1w"`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum BarInterval {
    /// `N` minutes per bar.
    Minute(u32),
    /// `N` hours per bar.
    Hour(u32),
    /// One day per bar.
    Day,
    /// One week per bar.
    Week,
}

impl BarInterval {
    /// The interval as a `chrono::Duration`, when representable.
    pub fn to_duration(&self) -> Option<Duration> {
        match *self {
            BarInterval::Minute(n) => Duration::try_minutes(i64::from(n)),
            BarInterval::Hour(n) => Duration::try_hours(i64::from(n)),
            BarInterval::Day => Duration::try_days(1),
            BarInterval::Week => Duration::try_days(7),
        }
    }
}

impl fmt::Display for BarInterval {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = match *self {
            BarInterval::Minute(n) => format!("{n}m"),
            BarInterval::Hour(n) => format!("{n}h"),
            BarInterval::Day => "1d".to_string(),
            BarInterval::Week => "1w".to_string(),
        };
        write!(f, "{}", s)
    }
}

impl FromStr for BarInterval {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        let s = s.trim();
        let (num, unit) = s.split_at(s.len().saturating_sub(1));
        let unit = unit.to_lowercase();
        let value: u32 = num.parse().map_err(|_| {
            format!("invalid bar interval '{s}' — expected e.g. '15m', '4h', '1d', '1w'")
        })?;
        if value == 0 {
            return Err(format!(
                "invalid bar interval '{s}' — magnitude must be positive"
            ));
        }
        match unit.as_str() {
            "m" => Ok(BarInterval::Minute(value)),
            "h" => Ok(BarInterval::Hour(value)),
            "d" if value == 1 => Ok(BarInterval::Day),
            "w" if value == 1 => Ok(BarInterval::Week),
            _ => Err(format!(
                "invalid bar interval '{s}' — expected e.g. '15m', '4h', '1d', '1w'"
            )),
        }
    }
}

impl Serialize for BarInterval {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(&self.to_string())
    }
}

impl<'de> Deserialize<'de> for BarInterval {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct IntervalVisitor;

        impl Visitor<'_> for IntervalVisitor {
            type Value = BarInterval;

            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                write!(
                    f,
                    "a bar interval string such as \"15m\", \"4h\", \"1d\" or \"1w\""
                )
            }

            fn visit_str<E: de::Error>(self, v: &str) -> Result<BarInterval, E> {
                BarInterval::from_str(v).map_err(E::custom)
            }
        }

        deserializer.deserialize_str(IntervalVisitor)
    }
}

