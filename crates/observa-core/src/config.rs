/// Errors produced by canonical configuration parsing/validation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum ConfigError {
    /// The raw input could not be parsed against the strict schema.
    Parse(String),
    /// The configuration schema version is not supported.
    UnsupportedVersion { found: u32, supported: u32 },
    /// A field failed semantic validation.
    InvalidField { field: String, reason: String },
    /// Account currency differs from the instrument quote currency and no FX
    /// conversion is available in the MVP.
    CurrencyMismatch { account: String, quote: String },
}

impl fmt::Display for ConfigError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            ConfigError::Parse(msg) => write!(f, "invalid configuration: {msg}"),
            ConfigError::UnsupportedVersion { found, supported } => write!(
                f,
                "unsupported configuration version {found} (supported: {supported})"
            ),
            ConfigError::InvalidField { field, reason } => {
                write!(f, "invalid configuration field '{field}': {reason}")
            }
            ConfigError::CurrencyMismatch { account, quote } => write!(
                f,
                "account currency '{account}' does not match instrument quote \
                 currency '{quote}'; currency conversion is outside the MVP — \
                 use a matching account currency"
            ),
        }
    }
}

impl std::error::Error for ConfigError {}

/// Validates a currency code: exactly three ASCII letters.
pub fn is_valid_currency_code(code: &str) -> bool {
    code.len() == 3
        && code
            .bytes()
            .all(|b| b.is_ascii_uppercase() && b.is_ascii_alphabetic())
}

fn validate_currency_code(code: &str, field: &str) -> Result<(), ConfigError> {
    if is_valid_currency_code(code) {
        Ok(())
    } else {
        Err(ConfigError::InvalidField {
            field: field.into(),
            reason: format!(
                "'{code}' is not a valid currency code (expected 3 uppercase ASCII letters)"
            ),
        })
    }
}

fn check_finite_positive(
    value: f64,
    field: &str,
    strictly_positive: bool,
) -> Result<(), ConfigError> {
    let ok = if strictly_positive {
        value.is_finite() && value > 0.0
    } else {
        value.is_finite() && value >= 0.0
    };
    if ok {
        Ok(())
    } else {
        Err(ConfigError::InvalidField {
            field: field.into(),
            reason: format!(
                "must be a finite {sign} number",
                sign = if strictly_positive {
                    "positive"
                } else {
                    "non-negative"
                }
            ),
        })
    }
}

fn check_non_negative(value: f64, field: &str) -> Result<(), ConfigError> {
    check_finite_positive(value, field, false)
}

