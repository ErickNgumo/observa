/// The canonical configuration of a backtest run.
///
/// One authoritative representation. Strict schema (unknown fields are
/// rejected by serde) plus explicit, deterministic defaults plus semantic
/// validation ([`BacktestConfig::validate`]).
///
/// `dataset` and `strategy` are optional at parse time because their identity
/// (hash, timestamps, parameters) is only known once the run is assembled;
/// the engine fills them before persisting the resolved configuration.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct BacktestConfig {
    /// Configuration schema version; must equal [`CONFIG_VERSION`].
    pub version: u32,
    /// Account configuration.
    #[serde(default)]
    pub account: AccountConfig,
    /// Instrument configuration.
    #[serde(default)]
    pub instrument: InstrumentConfig,
    /// Execution configuration.
    #[serde(default)]
    pub execution: ExecutionConfig,
    /// Dataset identity/metadata, filled by the data layer at run time.
    #[serde(default)]
    pub dataset: Option<DatasetConfig>,
    /// Strategy identity/parameters, filled at run assembly time.
    #[serde(default)]
    pub strategy: Option<StrategyConfig>,
}

impl Default for BacktestConfig {
    fn default() -> Self {
        Self {
            version: CONFIG_VERSION,
            account: AccountConfig::default(),
            instrument: InstrumentConfig::default(),
            execution: ExecutionConfig::default(),
            dataset: None,
            strategy: None,
        }
    }
}

impl BacktestConfig {
    /// Parses a canonical configuration from JSON.
    ///
    /// Unknown fields are rejected by the strict schema. YAML/other formats
    /// can use the same `Deserialize` impl at the consuming edge.
    pub fn from_json_str(input: &str) -> Result<Self, ConfigError> {
        serde_json::from_str(input).map_err(|e| ConfigError::Parse(e.to_string()))
    }

    /// Semantic validation of a parsed configuration.
    ///
    /// Structural validation (unknown fields, enum values) already happens
    /// during parsing; this method validates numeric/currency/relationship
    /// invariants and must be called before the configuration is used.
    pub fn validate(&self) -> Result<(), ConfigError> {
        // Version marker.
        if self.version != CONFIG_VERSION {
            return Err(ConfigError::UnsupportedVersion {
                found: self.version,
                supported: CONFIG_VERSION,
            });
        }

        // Account.
        let f = "account.starting_balance";
        check_finite_positive(self.account.starting_balance, f, false)?;
        validate_currency_code(&self.account.currency, "account.currency")?;
        check_finite_positive(self.account.leverage, "account.leverage", true)?;

        // Instrument.
        if self.instrument.symbol.trim().is_empty() {
            return Err(ConfigError::InvalidField {
                field: "instrument.symbol".into(),
                reason: "must be non-empty".into(),
            });
        }
        validate_currency_code(&self.instrument.base_currency, "instrument.base_currency")?;
        validate_currency_code(&self.instrument.quote_currency, "instrument.quote_currency")?;
        check_finite_positive(
            self.instrument.contract_size,
            "instrument.contract_size",
            true,
        )?;
        if self.instrument.price_decimals == 0 || self.instrument.price_decimals > 12 {
            return Err(ConfigError::InvalidField {
                field: "instrument.price_decimals".into(),
                reason: "must be between 1 and 12".into(),
            });
        }
        if let Some(tick) = self.instrument.tick_size {
            check_finite_positive(tick, "instrument.tick_size", true)?;
        }
        if let Some(pip) = self.instrument.pip_size {
            check_finite_positive(pip, "instrument.pip_size", true)?;
        }
        if let (Some(tick), Some(pip)) = (self.instrument.tick_size, self.instrument.pip_size) {
            if pip < tick {
                return Err(ConfigError::InvalidField {
                    field: "instrument.pip_size".into(),
                    reason: "pip_size must not be smaller than tick_size".into(),
                });
            }
        }
        // Quantity constraints: 0 ≤ min < max and a positive step that fits.
        let min_q = self.instrument.min_quantity;
        let max_q = self.instrument.max_quantity;
        let step = self.instrument.quantity_step;
        if !min_q.is_finite() || min_q < 0.0 {
            return Err(ConfigError::InvalidField {
                field: "instrument.min_quantity".into(),
                reason: "must be finite and >= 0".into(),
            });
        }
        if !max_q.is_finite() || max_q <= min_q {
            return Err(ConfigError::InvalidField {
                field: "instrument.max_quantity".into(),
                reason: "must be finite and greater than min_quantity".into(),
            });
        }
        if !step.is_finite() || step <= 0.0 || step > (max_q - min_q) {
            return Err(ConfigError::InvalidField {
                field: "instrument.quantity_step".into(),
                reason: "must be finite, > 0 and not larger than (max_quantity - min_quantity)"
                    .into(),
            });
        }

        // Execution.
        check_non_negative(self.execution.spread, "execution.spread")?;
        check_non_negative(self.execution.slippage, "execution.slippage")?;
        check_non_negative(
            self.execution.commission.flat_per_fill,
            "execution.commission.flat_per_fill",
        )?;
        check_non_negative(
            self.execution.commission.rate_per_unit,
            "execution.commission.rate_per_unit",
        )?;
        let om = &self.execution.order_model;
        if !om.market && !om.limit && !om.stop {
            return Err(ConfigError::InvalidField {
                field: "execution.order_model".into(),
                reason: "at least one order kind must be enabled".into(),
            });
        }

        // Currency compatibility (no FX conversion in the MVP).
        if self.account.currency != self.instrument.quote_currency {
            return Err(ConfigError::CurrencyMismatch {
                account: self.account.currency.clone(),
                quote: self.instrument.quote_currency.clone(),
            });
        }

        // Dataset.
        if let Some(ds) = &self.dataset {
            if ds.source.trim().is_empty() {
                return Err(ConfigError::InvalidField {
                    field: "dataset.source".into(),
                    reason: "must be non-empty".into(),
                });
            }
            if let (Some(start), Some(end)) = (ds.start, ds.end) {
                if start >= end {
                    return Err(ConfigError::InvalidField {
                        field: "dataset.start".into(),
                        reason: "dataset.start must be earlier than dataset.end".into(),
                    });
                }
            }
        }

        // Strategy.
        if let Some(st) = &self.strategy {
            if st.name.trim().is_empty() {
                return Err(ConfigError::InvalidField {
                    field: "strategy.name".into(),
                    reason: "must be non-empty".into(),
                });
            }
        }

        Ok(())
    }

    /// Returns a resolved copy with the dataset identity attached.
    pub fn with_dataset(mut self, dataset: DatasetConfig) -> Self {
        self.dataset = Some(dataset);
        self
    }

    /// Returns a resolved copy with the strategy identity attached.
    pub fn with_strategy(mut self, strategy: StrategyConfig) -> Self {
        self.strategy = Some(strategy);
        self
    }

    /// Convenience: does this configuration form a resolved (run-ready) config?
    pub fn is_resolved(&self) -> bool {
        self.dataset.is_some() && self.strategy.is_some()
    }
}

