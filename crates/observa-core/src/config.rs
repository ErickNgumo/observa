//! Canonical backtest configuration and dataset domain model.
//!
//! This module is the single authoritative configuration representation for
//! the Observa MVP (OBS-0003 / OBS-0004). Every component — engine,
//! execution, portfolio, metrics, persistence — consumes the types defined
//! here rather than crate-private configuration structs.
//!
//! The pipeline is:
//!
//! ```text
//! raw config (YAML/JSON)
//!      ↓  strict schema (unknown fields rejected) + explicit defaults
//! BacktestConfig
//!      ↓  `validate()` semantic validation
//! resolved canonical config (deterministically serializable)
//!      ↓  embedded in the persisted run (`run.json`)
//! ```
//!
//! Unit rules that this module enforces by construction:
//! * `units  = quantity_lots × contract_size`
//! * `notional = units × price`
//! * `margin_rate = 1 / leverage` (validation happens in OBS-0005)
//! * monetary value-per-pip/tick is *derived*, never a free input
//!
//! Money is expressed in the instrument quote currency, which must equal the
//! account currency in the MVP (no FX conversion). A configuration where the
//! two differ is rejected, never silently assumed equivalent.

use std::collections::BTreeMap;
use std::fmt;
use std::str::FromStr;

use chrono::{DateTime, Duration, Utc};
use serde::de::{self, Visitor};
use serde::{Deserialize, Deserializer, Serialize, Serializer};

use crate::types::OrderKind;

/// Current configuration schema version.
///
/// Persisted configurations are self-identifying via this marker. No
/// migration framework exists yet; parsers must reject configurations whose
/// version differs from [`CONFIG_VERSION`].
pub const CONFIG_VERSION: u32 = 1;

// ────────────────────────────────────────────────
// Fill mode
// ────────────────────────────────────────────────

/// The canonical MVP fill modes (OBS-0003 §8).
///
/// The historical "fill at the signal bar's open" behavior is deliberately
/// NOT representable here.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum FillMode {
    /// A market order generated by a strategy decision on bar `B` executes at
    /// the close of the same bar `B` (spread/slippage applied to the close).
    BarClose,
    /// A market order generated on bar `B` is queued and executes at the open
    /// of the next bar `B + 1`.
    NextBarOpen,
}

impl fmt::Display for FillMode {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        let s = match self {
            FillMode::BarClose => "BAR_CLOSE",
            FillMode::NextBarOpen => "NEXT_BAR_OPEN",
        };
        write!(f, "{}", s)
    }
}

impl FromStr for FillMode {
    type Err = String;

    fn from_str(s: &str) -> Result<Self, Self::Err> {
        match s.trim().to_uppercase().as_str() {
            "BAR_CLOSE" => Ok(FillMode::BarClose),
            "NEXT_BAR_OPEN" => Ok(FillMode::NextBarOpen),
            other => Err(format!(
                "unknown fill mode '{other}' — expected 'BAR_CLOSE' or 'NEXT_BAR_OPEN'"
            )),
        }
    }
}

// ────────────────────────────────────────────────
// Commission configuration
// ────────────────────────────────────────────────

/// When commission is charged relative to a round trip.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum CommissionMode {
    /// Commission is charged on every fill (entry and exit legs).
    PerSide,
    /// Commission is charged once per completed round trip.
    RoundTrip,
}

/// Canonical commission configuration.
///
/// Both flat and volume-based pricing are representable:
/// * `flat_per_fill` — money charged per fill (or per round trip, per mode),
/// * `rate_per_unit` — money per base unit, so that `$5 / 100,000 units` is
///   `rate_per_unit = 0.00005`.
///
/// The *amount* an execution must charge is
/// `commission = flat_per_fill + rate_per_unit × units` for the units of the
/// fill. Calculation and charging timing belong to OBS-0005/OBS-0006; this
/// configuration only has to represent them unambiguously.
#[derive(Debug, Clone, Copy, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CommissionConfig {
    /// Charging mode.
    pub mode: CommissionMode,
    /// Fixed money amount per charged event (default: 0).
    #[serde(default = "default_zero")]
    pub flat_per_fill: f64,
    /// Volume-based money rate per base unit (default: 0).
    #[serde(default = "default_zero")]
    pub rate_per_unit: f64,
}

impl Default for CommissionConfig {
    fn default() -> Self {
        Self {
            mode: CommissionMode::PerSide,
            flat_per_fill: 0.0,
            rate_per_unit: 0.0,
        }
    }
}

impl CommissionConfig {
    /// The commission amount attributable to a fill of `units` base units.
    ///
    /// This is the single calculation owner. Whether the amount is *charged*
    /// per side or per round trip is a decision of the charging logic
    /// (OBS-0005/OBS-0006), which must use this method and never recompute
    /// commission independently.
    pub fn amount_for_units(&self, units: f64) -> f64 {
        self.flat_per_fill + self.rate_per_unit * units
    }
}

